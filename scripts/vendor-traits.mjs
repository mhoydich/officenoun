const source = process.argv[2];
if (!source) throw new Error("usage: node scripts/vendor-traits.mjs path/to/image-data.json");
const data = JSON.parse(await readFile(source, "utf8"));

const library = { heads: data.images.heads, bodies: data.images.bodies, accessories: data.images.accessories, glasses: data.images.glasses };
const traits = { palette: data.palette.map((hex) => (hex ? `#${hex}` : "")) };
for (const [kind, labels] of Object.entries(pools)) {
  traits[kind] = Object.entries(labels).map(([filename, label]) => {
    const image = library[kind].find((item) => item.filename === filename);
    if (!image) throw new Error(`missing trait: ${filename}`);
    return { filename, label, data: image.data };
  });
}
if (traits.glasses.length !== data.images.glasses.length) throw new Error("glasses pool must cover every glasses trait");

const lines = Object.entries(traits).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`);
await writeFile(out, `// Generated by scripts/vendor-traits.mjs from @nouns/assets (CC0). Do not edit.\nglobalThis.OFFICE_TRAITS = {\n${lines.join(",\n")}\n};\n`);
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
