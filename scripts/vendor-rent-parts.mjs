// Dev tool, not part of the build. Writes public/rent/parts.js: the official CC0 Nouns traits the
// Temp Pool draws new nouns from in the chat ("make me a noun"). Heads skip the office's ten canon
// heads, so every chat noun is a face the office never had.
//   npm i --no-save @nouns/assets
//   node scripts/vendor-rent-parts.mjs node_modules/@nouns/assets/dist/image-data.json
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2];
if (!source) throw new Error("usage: node scripts/vendor-rent-parts.mjs <image-data.json>");
const data = JSON.parse(await readFile(source, "utf8"));
const canon = new Set(["head-calendar", "head-calculator", "head-stapler", "head-coffeebean", "head-cordlessphone", "head-mailbox", "head-mouse", "head-mug", "head-pencil-tip", "head-laptop"]);

// "head-fax-machine" -> "fax machine"; drops trailing variant letters and colour noise.
const label = (filename, prefix) => filename.slice(prefix.length + 1).replace(/-[a-z]$/i, "").replace(/[-_]+/g, " ").trim();
const pool = (kind, prefix, keep = () => true) => data.images[kind].filter((t) => keep(t.filename)).map((t) => [label(t.filename, prefix), t.data]);

const parts = {
  palette: data.palette,
  heads: pool("heads", "head", (f) => !canon.has(f)),
  bodies: pool("bodies", "body"),
  accessories: pool("accessories", "accessory"),
  glasses: pool("glasses", "glasses"),
};
const out = `/* CC0 Nouns traits for the Temp Pool's chat-drawn nouns. Generated by scripts/vendor-rent-parts.mjs; do not edit.
   Each entry is [label, rle data]. The office's ten canon heads are left out. Never reorder: drawn nouns are seeded by index. */
globalThis.NOUN_PARTS = ${JSON.stringify(parts)};
`;
await writeFile(path.join(root, "public/rent/parts.js"), out);
console.log(`wrote parts.js: ${parts.heads.length} heads, ${parts.bodies.length} bodies, ${parts.accessories.length} accessories, ${parts.glasses.length} glasses, ${(out.length / 1024).toFixed(0)} KB`);
